// Круги сырников из сохранённой формы дома (спецификация «Сладкий город», шаг Б, §7.1): смещение круга (ox, oz) каждого
// этажа от центра его прямоугольника выводится из записи формы (decodeShape) по тем же правилам, по которым его ведёт
// вид стройки (towerView: _inherit, _landCircle, шаг А §5.2). Формат сохранения не меняется: старые дома получают срезы
// на карте сразу. Чистое ядро: без three и без часов.
import { W0, D0 } from './levels.js';

/**
 * §5.2: |ox| ≤ (W0 − w)/2, |oz| ≤ (D0 − d)/2, затем |(ox, oz)| ≤ W0/2 − min(w, d)/4 — круг накрывает середину
 * этажа. → out ({ ox, oz }).
 */
export function clampOffset(ox, oz, w, d, out = { ox: 0, oz: 0 }) {
  const ax = Math.max(0, (W0 - w) / 2), az = Math.max(0, (D0 - d) / 2);
  let x = Math.min(ax, Math.max(-ax, ox)), z = Math.min(az, Math.max(-az, oz));
  const lim = Math.max(0, W0 / 2 - Math.min(w, d) / 4), len = Math.hypot(x, z);
  if (len > lim) { x *= lim / len; z *= lim / len; }
  out.ox = x + 0; // + 0: без −0
  out.oz = z + 0;
  return out;
}

// край считается срезанным, если срез больше этого; центры и размеры формы записаны по сантиметру, поэтому у
// несрезанного края остаётся шум до 1 см, и срезанным выбирается тот край, где срез больше
const SAME = 1e-6;
const _c = { ox: 0, oz: 0 };
// основание под этажом 0 (как в генераторе формы towerShape): этаж 0 садится на него так же, как остальные на верхний
const BASE = Object.freeze({ x: 0, z: 0, w: W0, d: D0 });

/**
 * Сдвиг центра падающего этажа относительно центра нового (lx − x по оси) при попадании. Падающий — размера верхнего
 * (size), новый — пересечение [a0, a1] на верхнем с центром c. Срезан левый выступ (левый край пересечения правее левого
 * края верхнего): левые края падающего и нового совпали, сдвиг (size − nsize)/2; срезан правый — −(size − nsize)/2;
 * края совпали — 0. Через размеры, а не координаты: у размеров ошибка округления формы вдвое меньше. Если после
 * округления разошлись оба края, срезанным считается тот, где срез больше (у несрезанного — шум округления).
 */
function landedShift(c, size, a0, a1) {
  const cl = a0 - (c - size / 2), cr = c + size / 2 - a1, half = (size - (a1 - a0)) / 2;
  if (cl > SAME && cl >= cr) return half;
  if (cr > SAME) return -half;
  return 0;
}

/**
 * Смещения кругов всех этажей: [ox0, oz0, ox1, oz1, …], длина 2n. floors — как из decodeShape ({ x, z, w, d, perfect, … }).
 * Каждый этаж наследует круг верхнего (у этажа 0 верхний — основание W0 × D0 без круга: этаж 0 при попадании
 * сдвигает круг так же, как вид стройки) и при попадании сдвигает его на сдвиг падающего относительно пересечения,
 * при «идеально» оставляет; затем ограничения §5.2.
 * Точно в обычных посадках (до сантиметра формы); после балкона с ростом и «Расширения» — приближённо, но круг
 * накрывает середину этажа (clampOffset). out — массив длины 2n для переиспользования (иначе новый).
 */
export function shapeCircles(floors, out = null) {
  const n = floors?.length ?? 0;
  const res = out && out.length >= 2 * n ? out : new Float64Array(2 * n);
  for (let i = 0; i < n; i++) {
    const t = i ? floors[i - 1] : BASE, f = floors[i];
    // наследство: круг верхнего в пределах его размера (у основания круга нет — по центру); падающий висит того же
    // размера, второй clampOffset — тождество
    if (i) clampOffset(res[2 * i - 2], res[2 * i - 1], t.w, t.d, _c);
    else { _c.ox = 0; _c.oz = 0; }
    let ox = _c.ox, oz = _c.oz;
    if (!f.perfect) {
      ox += landedShift(t.x, t.w, f.x - f.w / 2, f.x + f.w / 2);
      oz += landedShift(t.z, t.d, f.z - f.d / 2, f.z + f.d / 2);
    }
    clampOffset(ox, oz, f.w, f.d, _c);
    res[2 * i] = _c.ox;
    res[2 * i + 1] = _c.oz;
  }
  return res;
}

/** Круг верхнего этажа { ox, oz } (пустой список — (0, 0)). */
export function topCircle(floors) {
  const n = floors?.length ?? 0;
  if (!n) return { ox: 0, oz: 0 };
  const c = shapeCircles(floors);
  return { ox: c[2 * n - 2], oz: c[2 * n - 1] };
}

// ---------- начинки (спецификация «Сладкий город», шаг Б, §4.1) ----------

/** Начинка по типу дома; неизвестный тип — пудра ('sugar'). */
export const TOPPING_OF = Object.freeze({ house: 'sugar', shop: 'cream', office: 'jam', tower: 'berries' });
/**
 * Размеры начинок в мировых единицах (масштаб начинки s = 1) над верхом этажа: r — радиус следа, h — видимый верх
 * начинки, seat — высота опоры украшения (уходит в начинку). Одно правило высоты (задача 8): сетка начинки — высотой
 * h + TOPPING_SINK, её низ — на TOPPING_SINK · s под верхом этажа (в твороге), и над верхом этажа видна та же начинка,
 * что прошла ревью моделей (её низ стоял на верхе этажа): верх — h · s, опора украшения — seat · s (масштаб s — около
 * точки верха этажа в центре следа). Модели (задача 6, topping.py: sunk) строятся под эти числа, тест сверяет их с
 * сетками (±5 %). После ревью моделей (круги 1 и 2; было 1,05 / 0,55, 1,15 / 0,45 / 0,18, 1,15 / 0,85): след
 * сметаны — половина поперечника сырника, верх — 0,45 высоты сырника (1,3 м: ниже горка читалась шайбой); варенье —
 * плотная горка ягод (верх 0,45 высоты, прежние 0,35 — плёнка), опора украшения — в верхней малине; ягоды — след 1,0 и
 * верх 0,9 (0,69 высоты): ягоды крупнее и собраны тесной кучкой в этом следе (§4.1 — до 0,7 высоты).
 * После ревью вида r0 (задача 11, круг правок 1, Б2, В4, В5; числа — по кадрам против листов заказчика, §4.1; было
 * 1,0 / 0,58, 1,1, 1,0 / 0,9): сметана — горка из мешка, а не «тарелка»: след уже на 5 %, верх выше на 28 % (высота —
 * 0,39 поперечника, на листе 0,44; плечи — почти конус к носику, topping.py); у варенья лужица шире на 15 % (след —
 * 0,63 поперечника сырника): блестящий край виден вокруг ягод; ягоды — кучка как на листе: след 1,15, верх 1,0.
 * Доводка вида, задача 4, круг правок 2 ревью моделей (п. 3: в финале горка сметаны — «широкая низкая клякса», на
 * листе высота к поперечнику 0,42–0,44): верх сметаны 0,74 → 0,81 (0,43 поперечника), след прежний.
 */
export const TOPPINGS = Object.freeze({
  cream: Object.freeze({ r: 0.95, h: 0.81, seat: 0.3 }),
  jam: Object.freeze({ r: 1.26, h: 0.585, seat: 0.27 }),
  berries: Object.freeze({ r: 1.15, h: 1.0, seat: 0.3 }),
});
/** Отступ следа начинки от края этажа и радиус ровного верха сырника. */
export const TOPPING_MARGIN = 0.1;
export const TOPPING_FLAT = 1.6;
/**
 * Наименьший видимый радиус следа начинки r · s (меньше — пудра): граница — по видимому размеру, а не по масштабу. С
 * порогом масштаба 0,45 рост следа варенья и ягод (круг правок вида r1: 1,1 → 1,26, 1,0 → 1,15) отправил в пудру офис и
 * небоскрёб на узких верхах карты (ревью вида r1, Р1, И1): пудра там, где в r0 стояла начинка. Число — 0,45 · min(r0, r):
 * начинка там, где она была в r0 или в r1. Варенье 0,495 и ягоды 0,45 — граница r0 (их след вырос); сметана 0,4275 —
 * граница r1 (её след сузился с 1,0 до 0,95, и с 0,45 сметана ушла бы в пудру на одном доме, где была в r1; решение
 * R29). Одно правило для стройки и карты (toppingSpot).
 */
export const TOPPING_R_MIN = Object.freeze({ cream: 0.45 * 0.95, jam: 0.45 * 1.1, berries: 0.45 * 1.0 });
/**
 * Низ начинки уходит в творог (§4.3): низ — на TOPPING_SINK · s ниже верха этажа (s — масштаб начинки, toppingSpot);
 * сетка начинки на столько же длиннее книзу (TOPPINGS), так что видимая высота — h · s. Одно правило для стройки и
 * карты. Замер лучами (2026-11-16, подробная сетка сырника: пять клеток, оба полуоборота, восемь верхов — целые и
 * срезанные со смещённым кругом): верх сырника под нижним краем сметаны и варенья и под точками опоры ягод лежит до
 * 0,07–0,08 ниже верха этажа (ямки между комьями; у дальней сетки — до 0,06), на буграх — до 0,04 выше (у грани среза —
 * до 0,08). С 0,08 при s = 1 щели под начинкой нет нигде; у маленькой начинки на узком верхе осадка меньше, а ямки под
 * её следом почти те же: при s 0,45–0,6 щель — до 1,6 см у сметаны, 1,9 у ягод и 2,9 у варенья (замер задачи 8, верхи
 * 1,2–1,4 шириной; в кадре финала — около пикселя). С TOPPING_R_MIN масштаб на самом узком верхе ниже: варенье 0,395,
 * ягоды 0,393, сметана 0,453. Замер 2026-11-17 (верх 2 · (R_MIN + TOPPING_MARGIN) и шириной 4, и столь же узкий в
 * глубину; круг по центру и у краёв, оба полуоборота, три клетки; наибольшее по вершинам низа): стройка — варенье
 * 4,9 см (p90 3,1), ягоды 4,4 (3,1), сметана 3,8 (3,2); карта — 2,8, 2,3 и 2,4 см. При масштабе 0,45 там же — 4,5, 4,3,
 * 3,8 и 2,7, 1,5, 2,4: шире не больше чем на 0,8 см, а в кадре финала (около 50 пикселей на 4 м) 5 см — меньше пикселя.
 * Осадку на малом масштабе не держим (верх начинки ниже, а buildingTop, roofSpot и посадка жителей — на том же
 * правиле): граница щели — тест (syrnikTower.test.js: до 5,5 см в стройке, p90 до 3,5, до 3 см на карте и не шире
 * прежнего порога 0,45 больше чем на 1 см; ревью кода круга r2, Important 1).
 */
export const TOPPING_SINK = 0.08;
/**
 * Крыша золотого верхнего этажа лежит на меду (§5; задача 8): слой мёда приподнят над сырником до HONEY_LIFT
 * (syrnikGlaze GLAZE.honey.lift), пудра и начинка — выше на столько же; верх дома (buildingTop) и опора украшения
 * (roofSpot) — тоже. Одно число для стройки, карты и логики города.
 */
export const HONEY_LIFT = 0.02;

/**
 * Начинка на верхнем этаже top = { w, d } с кругом (ox, oz) от его центра (§4.1, §4.3): { kind, x, z, s } — x, z от
 * центра этажа. 'sugar' — пудра по центру, масштаб 1. Иначе масштаб s влезает в этаж с отступом TOPPING_MARGIN, центр —
 * круг, зажатый в прямоугольник, и след целиком в ровном верху (TOPPING_FLAT от центра круга); видимый радиус r · s
 * меньше TOPPING_R_MIN — пудра.
 */
export function toppingSpot(type, top, ox = 0, oz = 0) {
  const kind = TOPPING_OF[type] ?? 'sugar';
  if (kind === 'sugar') return { kind, x: 0, z: 0, s: 1 };
  const t = TOPPINGS[kind], w = top?.w ?? W0, d = top?.d ?? D0;
  let s = Math.min(1, (Math.min(w, d) / 2 - TOPPING_MARGIN) / t.r);
  const lx = Math.max(0, w / 2 - t.r * s - TOPPING_MARGIN), lz = Math.max(0, d / 2 - t.r * s - TOPPING_MARGIN);
  const x = Math.min(lx, Math.max(-lx, ox)), z = Math.min(lz, Math.max(-lz, oz));
  const dist = Math.hypot(x - ox, z - oz);
  if (dist + t.r * s > TOPPING_FLAT) s = (TOPPING_FLAT - dist) / t.r;
  return t.r * s < TOPPING_R_MIN[kind] - 1e-9 ? { kind: 'sugar', x: 0, z: 0, s: 1 } : { kind, x: x + 0, z: z + 0, s };
}
